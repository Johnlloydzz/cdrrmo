import { useState, useEffect, useCallback } from 'react'
import { Printer, FileDown, RefreshCw } from 'lucide-react'
import { apiGet } from '../utils/api'
import { ROLE_PERMISSIONS } from '../data/users'
import DropdownSelect from '../components/DropdownSelect'

const HAZARDS = [{ id: 'flood', label: 'Flood' }, { id: 'landslide', label: 'Landslide' }]
const BASES = [
  { id: 'planning', label: 'Hazard-prone areas (planning)' },
  { id: 'live', label: 'Current alert (live)' },
]

const n = v => Number(v || 0).toLocaleString()
const fmtDate = iso => new Date(iso).toLocaleString('en-PH', { timeZone: 'Asia/Manila', dateStyle: 'long', timeStyle: 'short' })

const csvCell = v => { const s = String(v ?? ''); return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s }

function situationText(d) {
  const { hazard, basis } = d.filters
  if (hazard === 'landslide') return 'Landslide uses the official CDRA classification of each purok. There is no live landslide reading.'
  if (basis === 'planning') return 'Planning view: every purok inside the flood area drawn from the CDRA flood map, as if heavy rain hit now. It does not depend on today’s weather.'
  if (d.situation.simulate_rain) return 'A drill (Simulate heavy rain) is running, so every barangay counts as having heavy rain.'
  if (d.situation.flagged_barangays > 0) return `Heavy rain with a high river was detected in ${d.situation.flagged_barangays} barangay(s) right now. Only their flood-area puroks are counted.`
  return 'No heavy rain with a high river is detected right now, so no household is flagged. Use the planning view to see the flood-prone households.'
}

function buildCsv(d) {
  const f = d.filters, s = d.summary, dm = s.demographics
  const rows = [
    ['PDRA - Households at Risk (Potentially Affected) - Pre-Disaster Report'],
    ['Gingoog City CDRRMO'],
    ['Generated', fmtDate(d.generated_at)], ['Generated by', `${d.generated_by} (${d.role})`],
    ['Hazard', f.hazard === 'flood' ? 'Flood' : 'Landslide'],
    ['Basis', f.hazard === 'landslide' ? 'CDRA classification' : (f.basis === 'planning' ? 'Hazard-prone areas (planning)' : 'Current alert (live)')],
    ['Barangay', f.barangay_name || 'All barangays'], ['Purok', f.purok_name || 'All puroks'], [],
    ['SUMMARY'],
    ['Barangays at risk', s.barangays_at_risk, 'of', s.barangays_in_scope],
    ['Puroks at risk', s.puroks_at_risk, 'of', s.puroks_total],
    ['Households at risk', s.households_at_risk, 'of', s.households_total],
    ['Residents at risk', s.residents_at_risk, 'of', s.residents_total],
    ['Child (1-12)', dm.child], ['Teen (13-17)', dm.teen], ['Adult (18-59)', dm.adult], ['Senior (60+)', dm.senior],
    ['Age not recorded', dm.unknown_age], ['Male', dm.male], ['Female', dm.female], [],
    ['BY PUROK'], ['Barangay', 'Purok', 'Households', 'Residents', 'Status'],
    ...d.by_purok.map(p => [p.barangay_name, p.purok_name, p.households, p.residents, p.at_risk ? 'At risk' : 'Not at risk']), [],
    ['HOUSEHOLDS AT RISK'], ['HH No.', 'Barangay', 'Purok', 'Head of Family', 'Members', 'Contact'],
    ...d.households.map(h => [h.hh_label, h.barangay_name, h.purok_name, h.head_family, h.members, h.contact]),
  ]
  return '\ufeff' + rows.map(r => r.map(csvCell).join(',')).join('\r\n')
}

function downloadCsv(d) {
  const blob = new Blob([buildCsv(d)], { type: 'text/csv;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `PDRA_Households_at_Risk_${d.filters.hazard}_${new Date().toLocaleDateString('sv-SE', { timeZone: 'Asia/Manila' })}.csv`
  document.body.appendChild(a); a.click(); a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

const Seg = ({ options, value, onChange }) => (
  <div className="inline-flex rounded-lg border border-gray-200 overflow-hidden bg-white">
    {options.map(o => (
      <button key={o.id} type="button" onClick={() => onChange(o.id)}
        className={`px-3 py-1.5 text-sm font-medium ${value === o.id ? 'bg-blue-600 text-white' : 'text-gray-600 hover:bg-gray-50'}`}>{o.label}</button>
    ))}
  </div>
)

const Stat = ({ label, value, of, tone = 'text-gray-800' }) => (
  <div className="bg-white rounded-2xl border border-gray-100 shadow-sm p-4 text-center">
    <p className={`text-2xl font-bold ${tone}`}>{n(value)}</p>
    <p className="text-xs text-gray-500 mt-0.5">{label}</p>
    {of !== undefined && <p className="text-[11px] text-gray-400">of {n(of)}</p>}
  </div>
)

export default function Reports({ currentUser }) {
  const canExport = !!ROLE_PERMISSIONS[currentUser?.role]?.canExport
  const [hazard, setHazard] = useState('flood')
  const [basis, setBasis] = useState('planning')
  const [barangayId, setBarangayId] = useState('')
  const [purokId, setPurokId] = useState('')
  const [barangays, setBarangays] = useState([])
  const [puroks, setPuroks] = useState([])
  const [data, setData] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  useEffect(() => { apiGet('/barangays').then(r => setBarangays(Array.isArray(r) ? r : [])).catch(() => {}) }, [])
  useEffect(() => {
    setPurokId('')
    if (!barangayId) { setPuroks([]); return }
    apiGet(`/risk-assessment/puroks?barangay_id=${barangayId}`).then(r => setPuroks(Array.isArray(r) ? r : [])).catch(() => setPuroks([]))
  }, [barangayId])

  const load = useCallback(() => {
    setLoading(true); setError('')
    const q = new URLSearchParams({ hazard, basis })
    if (barangayId) q.set('barangay_id', barangayId)
    if (purokId) q.set('purok_id', purokId)
    return apiGet(`/reports/households-at-risk?${q}`)
      .then(setData).catch(e => setError(e.message || 'Could not load the report')).finally(() => setLoading(false))
  }, [hazard, basis, barangayId, purokId])
  useEffect(() => { load() }, [load])

  const s = data?.summary, dm = s?.demographics

  return (
    <div className="space-y-4">
      <style>{`
        .pr-only { display: none; }
        @page { size: A4; margin: 12mm; }
        @media print {
          body * { visibility: hidden; }
          #pdra-report, #pdra-report * { visibility: visible; }
          #pdra-report { position: absolute; left: 0; top: 0; width: 100%; }
          .no-print { display: none !important; }
          .pr-only { display: block !important; }
          #pdra-report table { font-size: 11px; }
          #pdra-report tr { break-inside: avoid; }
          #pdra-report thead { display: table-header-group; }
        }
      `}</style>

      {/* Filters and actions (not printed) */}
      <div className="no-print bg-white rounded-2xl border border-gray-100 shadow-sm p-4 space-y-3">
        <div className="flex flex-wrap items-center gap-3">
          <Seg options={HAZARDS} value={hazard} onChange={setHazard} />
          {hazard === 'flood' && <Seg options={BASES} value={basis} onChange={setBasis} />}
          <div className="ml-auto flex items-center gap-2">
            <button type="button" className="btn-secondary flex items-center gap-1.5" onClick={load} disabled={loading}>
              <RefreshCw size={15} className={loading ? 'animate-spin' : ''} /> Refresh
            </button>
            {canExport && (
              <>
                <button type="button" className="btn-secondary flex items-center gap-1.5" disabled={!data} onClick={() => downloadCsv(data)}>
                  <FileDown size={15} /> CSV (Excel)
                </button>
                <button type="button" className="btn-primary flex items-center gap-1.5" disabled={!data} onClick={() => window.print()}>
                  <Printer size={15} /> Print / Save as PDF
                </button>
              </>
            )}
          </div>
        </div>
        {currentUser?.role !== 'Barangay Official' && (
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 max-w-2xl">
            <DropdownSelect searchable value={barangayId} placeholder="All barangays"
              options={barangays.map(b => ({ value: b.id, label: b.name }))}
              onChange={v => setBarangayId(v === '' ? '' : String(v))} />
            <DropdownSelect value={purokId} placeholder={barangayId ? 'All puroks' : 'Pick a barangay first'}
              options={puroks.map(p => ({ value: p.purok_id, label: p.purok_name }))}
              onChange={v => setPurokId(v === '' ? '' : String(v))} />
          </div>
        )}
      </div>

      {error && <div className="no-print rounded-xl bg-red-50 border border-red-200 text-red-700 text-sm p-3">{error}</div>}
      {!data && loading && <p className="text-sm text-gray-500">Loading report…</p>}

      {data && (
        <div id="pdra-report" className={`space-y-4 ${loading ? 'opacity-60' : ''}`}>
          <div className="pr-only text-center border-b border-gray-300 pb-2">
            <p className="text-sm font-semibold">PDRA · Pre-Disaster Risk Assessment System</p>
            <p className="text-xs">Gingoog City CDRRMO</p>
          </div>
          <div>
            <h2 className="text-xl font-bold text-gray-800">Households at Risk (Potentially Affected)</h2>
            <p className="text-sm text-gray-500">Pre-disaster report · {data.filters.hazard === 'flood' ? 'Flood' : 'Landslide'} · {data.filters.barangay_name || 'All barangays'}{data.filters.purok_name ? ` · ${data.filters.purok_name}` : ''}</p>
            <p className="text-xs text-gray-400 mt-0.5">Generated {fmtDate(data.generated_at)} by {data.generated_by} ({data.role})</p>
          </div>

          <p className="text-sm text-gray-600 bg-blue-50 border border-blue-100 rounded-xl p-3">{situationText(data)}</p>

          <div className="grid grid-cols-2 lg:grid-cols-4 gap-3">
            <Stat label="Households at risk" value={s.households_at_risk} of={s.households_total} tone="text-red-600" />
            <Stat label="Residents at risk" value={s.residents_at_risk} of={s.residents_total} tone="text-red-600" />
            <Stat label="Puroks at risk" value={s.puroks_at_risk} of={s.puroks_total} tone="text-amber-600" />
            <Stat label="Barangays at risk" value={s.barangays_at_risk} of={s.barangays_in_scope} tone="text-amber-600" />
          </div>

          <div className="bg-white rounded-2xl border border-gray-100 shadow-sm p-4">
            <h3 className="text-sm font-semibold text-gray-700 mb-2">Residents at risk, by age group and sex</h3>
            <div className="grid grid-cols-2 sm:grid-cols-4 lg:grid-cols-7 gap-3 text-center">
              {[['Child (1-12)', dm.child], ['Teen (13-17)', dm.teen], ['Adult (18-59)', dm.adult], ['Senior (60+)', dm.senior], ['Male', dm.male], ['Female', dm.female], ['Age not recorded', dm.unknown_age]].map(([l, v]) => (
                <div key={l}><p className="text-lg font-bold text-gray-800">{n(v)}</p><p className="text-[11px] text-gray-500">{l}</p></div>
              ))}
            </div>
          </div>

          <div className="bg-white rounded-2xl border border-gray-100 shadow-sm overflow-x-auto">
            <h3 className="text-sm font-semibold text-gray-700 p-4 pb-2">Summary by purok</h3>
            <table className="w-full text-sm">
              <thead><tr className="text-left text-xs text-gray-500 border-y border-gray-100">
                <th className="px-4 py-2">Barangay</th><th className="px-4 py-2">Purok</th>
                <th className="px-4 py-2 text-right">Households</th><th className="px-4 py-2 text-right">Residents</th><th className="px-4 py-2">Status</th>
              </tr></thead>
              <tbody>
                {data.by_purok.length === 0 && <tr><td colSpan={5} className="px-4 py-4 text-gray-400">No puroks found for this selection.</td></tr>}
                {data.by_purok.map((p, i) => (
                  <tr key={i} className="border-b border-gray-50">
                    <td className="px-4 py-2">{p.barangay_name}</td><td className="px-4 py-2">{p.purok_name}</td>
                    <td className="px-4 py-2 text-right">{n(p.households)}</td><td className="px-4 py-2 text-right">{n(p.residents)}</td>
                    <td className="px-4 py-2">{p.at_risk
                      ? <span className="px-2 py-0.5 rounded-full text-xs font-medium bg-red-50 text-red-700">At risk</span>
                      : <span className="px-2 py-0.5 rounded-full text-xs font-medium bg-gray-100 text-gray-500">Not at risk</span>}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <div className="bg-white rounded-2xl border border-gray-100 shadow-sm overflow-x-auto">
            <h3 className="text-sm font-semibold text-gray-700 p-4 pb-2">Households at risk ({n(data.households.length)})</h3>
            <table className="w-full text-sm">
              <thead><tr className="text-left text-xs text-gray-500 border-y border-gray-100">
                <th className="px-4 py-2">HH No.</th><th className="px-4 py-2">Barangay</th><th className="px-4 py-2">Purok</th>
                <th className="px-4 py-2">Head of Family</th><th className="px-4 py-2 text-right">Members</th><th className="px-4 py-2">Contact</th>
              </tr></thead>
              <tbody>
                {data.households.length === 0 && <tr><td colSpan={6} className="px-4 py-4 text-gray-400">No household is inside a hazard area for this selection.</td></tr>}
                {data.households.map((h, i) => (
                  <tr key={i} className="border-b border-gray-50">
                    <td className="px-4 py-2 font-mono text-xs text-blue-700">{h.hh_label}</td><td className="px-4 py-2">{h.barangay_name}</td>
                    <td className="px-4 py-2">{h.purok_name}</td><td className="px-4 py-2 font-medium">{h.head_family}</td>
                    <td className="px-4 py-2 text-right">{n(h.members)}</td><td className="px-4 py-2">{h.contact || '—'}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <div className="pr-only pt-10">
            <div className="flex justify-between text-xs">
              <div className="w-64 text-center"><div className="border-t border-gray-500 pt-1">Prepared by: {data.generated_by}</div></div>
              <div className="w-64 text-center"><div className="border-t border-gray-500 pt-1">Noted by</div></div>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}